class FoodItemData {
  final String image;
  final double startX;
  final double startY;
  final double endX;
  final double endy;
  final double delay;
  final double arcHeight;
  final double rotation;
  final double rotationSpeed;
  final double size;

  FoodItemData({
    required this.image,
    required this.startX,
    required this.startY,
    required this.endX,
    required this.endy,
    required this.delay,
    required this.arcHeight,
    required this.rotation,
    required this.rotationSpeed,
    required this.size,
  });
}
